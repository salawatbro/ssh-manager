const cfgPath = "/Users/me/Library/Caches/SSHManager/launch/5c1e/ssh_config"

func opts() Options {
	return Options{SSHPath: SSHPath, HomeDir: "/Users/me", ConnectTimeout: 10, KeepAlive: true}
}

func srv(id, user, host string, port int, auth domain.AuthType, key string) domain.Server {
	return domain.Server{ID: id, Name: id, User: user, Host: host, Port: port, AuthType: auth, KeyPath: key}
}

func TestBuildPlanSingleServer(t *testing.T) {
	keepalive := []string{"-o", "ConnectTimeout=10", "-o", "ServerAliveInterval=30", "-o", "ServerAliveCountMax=3"}
	twoFA := srv("db", "root", "db.internal", 22, domain.AuthPassword, "")
	twoFA.TwoFactor = true
	keyTwoFA := srv("k", "deploy", "10.0.1.20", 2222, domain.AuthKey, "~/.ssh/id_ed25519")
	keyTwoFA.TwoFactor = true
	cases := []struct {
		name string
		s    domain.Server
		o    Options
		argv []string
		hop  askpass.Hop
	}{
		{
			name: "password",
			s:    srv("pw", "root", "db.internal", 22, domain.AuthPassword, ""),
			o:    opts(),
			argv: append(append([]string{SSHPath}, keepalive...), "-o", "PreferredAuthentications=password,keyboard-interactive", "-p", "22", "-l", "root", "--", "db.internal"),
			hop:  askpass.Hop{ServerID: "pw", User: "root", Host: "db.internal", Password: true},
		},
		{
			name: "password + 2FA",
			s:    twoFA,
			o:    opts(),
			argv: append(append([]string{SSHPath}, keepalive...), "-o", "PreferredAuthentications=password,keyboard-interactive", "-p", "22", "-l", "root", "--", "db.internal"),
			hop:  askpass.Hop{ServerID: "db", User: "root", Host: "db.internal", Password: true, TOTP: true},
		},
		{
			name: "key + 2FA on a non-default port",
			s:    keyTwoFA,
			o:    opts(),
			argv: append(append([]string{SSHPath}, keepalive...), "-o", "IdentitiesOnly=yes", "-o", `IdentityFile="/Users/me/.ssh/id_ed25519"`, "-p", "2222", "-l", "deploy", "--", "10.0.1.20"),
			hop:  askpass.Hop{ServerID: "k", User: "deploy", Host: "10.0.1.20", KeyPath: "/Users/me/.ssh/id_ed25519", Passphrase: true, TOTP: true},
		},
		{
			name: "agent, no timeout, keep-alive off, IPv6",
			s:    srv("a", "ops", "2001:db8::1", 0, domain.AuthAgent, ""),
			o:    Options{HomeDir: "/Users/me"},
			argv: []string{SSHPath, "-p", "22", "-l", "ops", "--", "2001:db8::1"},
			hop:  askpass.Hop{ServerID: "a", User: "ops", Host: "2001:db8::1"},
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			p, err := BuildPlan([]domain.Server{c.s}, c.o, "")
			if err != nil {
				t.Fatal(err)
			}
			if !slices.Equal(p.Argv, c.argv) {
				t.Fatalf("argv = %q\nwant   %q", p.Argv, c.argv)
			}
			if p.Config != nil || len(p.Hops) != 1 || p.Hops[0] != c.hop {
				t.Fatalf("config %q hops %+v", p.Config, p.Hops)
			}
		})
	}
}

func TestBuildPlanJumpChainGolden(t *testing.T) {
	bastion := srv("b", "bastion", "10.0.0.1", 2222, domain.AuthKey, "~/.ssh/bastion_ed25519")
	jump2 := srv("j", "ops", "jump2.internal", 22, domain.AuthPassword, "")
	target := srv("t", "root", "db.internal", 22, domain.AuthPassword, "")
	target.TwoFactor = true

	p, err := BuildPlan([]domain.Server{bastion, jump2, target}, opts(), cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	wantArgv := []string{
		SSHPath, "-F", cfgPath, "-J", "zish-hop-1,zish-hop-2",
		"-o", "ConnectTimeout=10", "-o", "ServerAliveInterval=30", "-o", "ServerAliveCountMax=3",
		"-o", "PreferredAuthentications=password,keyboard-interactive",
		"-p", "22", "-l", "root", "--", "db.internal",
	}
	if !slices.Equal(p.Argv, wantArgv) {
		t.Fatalf("argv = %q\nwant   %q", p.Argv, wantArgv)
	}
	wantCfg := `# Generated by Zish for one connection; deleted automatically.
Host zish-hop-1
  HostName "10.0.0.1"
  Port 2222
  User "bastion"
  IdentitiesOnly yes
  IdentityFile "/Users/me/.ssh/bastion_ed25519"
Host zish-hop-2
  HostName "jump2.internal"
  Port 22
  User "ops"
  PreferredAuthentications password,keyboard-interactive
Host *
  ConnectTimeout 10
  ServerAliveInterval 30
  ServerAliveCountMax 3
  Include ~/.ssh/config
  Include /etc/ssh/ssh_config
`
	if string(p.Config) != wantCfg {
		t.Fatalf("config =\n%s\nwant\n%s", p.Config, wantCfg)
	}
	wantHops := []askpass.Hop{
		{ServerID: "b", User: "bastion", Host: "10.0.0.1", KeyPath: "/Users/me/.ssh/bastion_ed25519", Passphrase: true},
		{ServerID: "j", User: "ops", Host: "jump2.internal", Password: true},
		{ServerID: "t", User: "root", Host: "db.internal", Password: true, TOTP: true},
	}
	if !slices.Equal(p.Hops, wantHops) {
		t.Fatalf("hops = %+v", p.Hops)
	}
}

func TestBuildPlanChainLengths(t *testing.T) {
	for _, n := range []int{1, 3, 8} {
		chain := make([]domain.Server, n)
		for i := range chain {
			chain[i] = srv("s"+strconv.Itoa(i), "u", "h"+strconv.Itoa(i)+".example", 22, domain.AuthAgent, "")
		}
		p, err := BuildPlan(chain, opts(), cfgPath)
		if err != nil {
			t.Fatal(err)
		}
		if n == 1 {
			if slices.Contains(p.Argv, "-J") || p.Config != nil {
				t.Fatalf("single server has jump args: %q", p.Argv)
			}
			continue
		}
		j := slices.Index(p.Argv, "-J")
		var want []string
		for i := 1; i < n; i++ {
			want = append(want, "zish-hop-"+strconv.Itoa(i))
		}
		if j < 0 || p.Argv[j+1] != strings.Join(want, ",") {
			t.Fatalf("n=%d: -J list = %q", n, p.Argv)
		}
		if got := strings.Count(string(p.Config), "\nHost zish-hop-"); got != n-1 {
			t.Fatalf("n=%d: %d hop blocks", n, got)
		}
	}
}

// No server value may reach a place where ssh or a shell would interpret it.
func TestBuildPlanHostileValues(t *testing.T) {
	hostileKey := "~/.ssh/k'ey \"q\" $(id) `id` %h \\ ünï"
	jump := srv("j", "jo hn$x%h", "10.0.0.1", 22, domain.AuthKey, hostileKey)
	target := srv("t", "o'brien; rm -rf ~", "db.internal", 22, domain.AuthKey, hostileKey)
	p, err := BuildPlan([]domain.Server{jump, target}, opts(), cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	n := len(p.Argv)
	if p.Argv[n-2] != "--" || p.Argv[n-1] != "db.internal" || p.Argv[n-3] != "o'brien; rm -rf ~" || p.Argv[n-4] != "-l" {
		t.Fatalf("argv tail = %q", p.Argv[n-6:])
	}
	if !slices.Contains(p.Argv, `IdentityFile="/Users/me/.ssh/k'ey \"q\" $(id) `+"`id`"+` %%h \\ ünï"`) {
		t.Fatalf("key not encoded: %q", p.Argv)
	}
	if j := slices.Index(p.Argv, "-J"); p.Argv[j+1] != "zish-hop-1" {
		t.Fatalf("-J carries data: %q", p.Argv[j+1])
	}
	// Each config line must tokenize to exactly keyword + one value.
	for _, line := range strings.Split(strings.TrimSpace(string(p.Config)), "\n") {
		if strings.HasPrefix(line, "#") {
			continue
		}
		toks, err := opensshArgvSplit(line, true)
		if err != nil || len(toks) != 2 {
			t.Fatalf("config line %q -> %q, %v", line, toks, err)
		}
	}
	if !strings.Contains(string(p.Config), `User "jo hn$x%%h"`) {
		t.Fatalf("config:\n%s", p.Config)
	}
	if p.Hops[1].KeyPath != "/Users/me/.ssh/k'ey \"q\" $(id) `id` %h \\ ünï" {
		t.Fatalf("hop key path = %q", p.Hops[1].KeyPath)
	}
}

func TestBuildPlanRejectsUnsafeValues(t *testing.T) {
	ok := srv("t", "root", "db.internal", 22, domain.AuthKey, "/k")
	mutate := []struct {
		name string
		f    func(*domain.Server)
	}{
		{"leading dash user", func(s *domain.Server) { s.User = "-oProxyCommand=touch /tmp/x" }},
		{"empty user", func(s *domain.Server) { s.User = "" }},
		{"newline user", func(s *domain.Server) { s.User = "root\nProxyCommand x" }},
		{"host with space", func(s *domain.Server) { s.Host = "db internal" }},
		{"host option", func(s *domain.Server) { s.Host = "-oProxyCommand=x" }},
		{"host subshell", func(s *domain.Server) { s.Host = "$(id)" }},
		{"host quote", func(s *domain.Server) { s.Host = "a'b" }},
		{"key newline", func(s *domain.Server) { s.KeyPath = "/k\nProxyCommand x" }},
		{"key env", func(s *domain.Server) { s.KeyPath = "${HOME}/k" }},
		{"port", func(s *domain.Server) { s.Port = 70000 }},
	}
	for _, m := range mutate {
		t.Run(m.name, func(t *testing.T) {
			s := ok
			m.f(&s)
			if _, err := BuildPlan([]domain.Server{s}, opts(), ""); !isUnsafe(err) {
				t.Fatalf("target: err = %v", err)
			}
			if _, err := BuildPlan([]domain.Server{s, ok}, opts(), cfgPath); !isUnsafe(err) {
				t.Fatalf("jump: err = %v", err)
			}
		})
	}
	if _, err := BuildPlan([]domain.Server{ok, ok}, opts(), "/Users/John Smith/cfg"); !isUnsafe(err) {
		t.Fatalf("unsafe config path: err = %v", err)
	}
}

func TestExpandHome(t *testing.T) {
	cases := map[string]string{
		"~":          "/Users/me",
		"~/.ssh/id":  "/Users/me/.ssh/id",
		"~bob/.ssh":  "~bob/.ssh",
		"/abs/id":    "/abs/id",
		"rel/id":     "rel/id",
		"a~/b":       "a~/b",
		"~/sp ace/k": "/Users/me/sp ace/k",
	}
	for in, want := range cases {
		if got := ExpandHome(in, "/Users/me"); got != want {
			t.Errorf("ExpandHome(%q) = %q, want %q", in, got, want)
		}
	}
}
